/* ------------------------------------------------------- time helpers */

const NOW = Date.now();
const H = 3600e3;
const M = 60e3;
/** ISO timestamp `n` hours in the past. */
const hAgo = (n: number) => new Date(NOW - n * H).toISOString();
/** ISO timestamp `n` hours in the future. */
const hIn = (n: number) => new Date(NOW + n * H).toISOString();
const mAgo = (n: number) => new Date(NOW - n * M).toISOString();

/** Derive SLA due dates from createdAt + policy (single source of truth). */
function slaDue(createdAtIso: string, priority: TicketPriority) {
  const spec = SUPPORT_SLA_POLICY[priority];
  const created = new Date(createdAtIso).getTime();
  return {
    firstResponseDueAt: new Date(created + spec.firstResponseMinutes * M).toISOString(),
    resolutionDueAt: new Date(created + spec.resolutionHours * H).toISOString(),
  };
}

